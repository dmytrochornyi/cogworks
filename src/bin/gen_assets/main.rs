//! Generates every sprite and sound for Cogworks into `assets/`, plus `src/assets_list.rs`
//! which embeds them in the game. Run with `cargo run --release --bin gen_assets`.

#[path = "../../theme.rs"]
mod theme;

mod audio;
mod paint;
mod sprites;

use std::fmt::Write as _;
use std::fs;

use paint::Canvas;

const ITEMS: &[&str] = &[
    "iron_ore", "copper_ore", "coal", "stone", "quartz", "iron_plate", "copper_plate", "brick",
    "steel", "glass", "gear", "wire", "rod", "circuit", "motor", "lens", "polymer", "processor",
    "fuel_cell", "slug_clip", "heavy_clip", "aether_core", "survey_data", "mech_data",
    "optic_data", "quantum_data",
];

const SFX: &[&str] = &["place", "pickup", "craft", "research", "shot", "click"];

fn main() {
    fs::create_dir_all("assets/sprites").unwrap();
    fs::create_dir_all("assets/audio").unwrap();

    let mut sheet: Vec<(String, Canvas)> = Vec::new();
    let mut add = |name: &str, cv: Canvas| sheet.push((name.to_string(), cv));

    let ground = sprites::ground_sheet();
    for j in 0..4 {
        for i in 0..4 {
            add(&format!("grass_{i}_{j}"), ground.crop(i * 64, j * 64, 64, 64));
        }
    }
    for v in 0..8 {
        add(&format!("decor_{v}"), sprites::decor(v));
    }
    for ore in ["iron", "copper", "coal", "stone", "quartz"] {
        for v in 0..3 {
            add(&format!("ore_{ore}_{v}"), sprites::ore(ore, v));
        }
    }
    for v in 0..2 {
        add(&format!("tar_{v}"), sprites::tar(v));
    }
    for f in 0..8 {
        add(&format!("belt_{f}"), sprites::belt(f));
        add(&format!("belt_curve_{f}"), sprites::belt_curve(f));
    }
    add("tunnel", sprites::tunnel());
    add("splitter", sprites::splitter());
    add("arm_base", sprites::arm_base());
    add("arm_limb", sprites::arm_limb());
    add("arm_hand", sprites::arm_hand());
    add("chest", sprites::chest());
    add("pipe_hub", sprites::pipe_hub());
    add("pipe_seg", sprites::pipe_seg());
    add("port_in", sprites::port(true));
    add("port_out", sprites::port(false));
    add("drill", sprites::drill());
    add("drill_bit", sprites::drill_bit());
    add("chute", sprites::chute());
    add("smelter", sprites::smelter());
    add("assembler", sprites::assembler());
    add("assembler_gear", sprites::gear_overlay(96, 10, paint::MUSTARD));
    add("lab", sprites::lab());
    add("lab_orb", sprites::orb(64, paint::hex(theme::QUARTZ_LIGHT), paint::hex(theme::TEAL)));
    add("generator", sprites::generator());
    add("generator_wheel", sprites::wheel());
    add("pole", sprites::pole());
    add("solar", sprites::solar());
    add("wellhead", sprites::wellhead());
    add("wellhead_beam", sprites::beam());
    add("refinery", sprites::refinery());
    add("mixer", sprites::mixer());
    add("mixer_paddle", sprites::paddle());
    add("wall", sprites::wall());
    add("sentry_base", sprites::sentry_base());
    add("sentry_head", sprites::sentry_head());
    add("engine", sprites::engine());
    add("engine_ring", sprites::engine_ring());
    add("engine_core", sprites::orb(96, paint::hex(theme::AETHER_HI), paint::hex(theme::AETHER_LO)));
    add("hive", sprites::hive());
    for f in 0..2 {
        add(&format!("player_{f}"), sprites::player(f));
        add(&format!("mite_{f}"), sprites::mite(f, false));
        add(&format!("brute_{f}"), sprites::mite(f, true));
    }
    for item in ITEMS {
        add(&format!("item_{item}"), sprites::item(item));
    }
    add("glow", sprites::soft_glow());
    add("smoke", sprites::smoke());
    add("cloud", sprites::cloud());
    for icon in ["heart", "flask", "bolt", "note"] {
        add(&format!("icon_{icon}"), sprites::icon(icon));
    }

    let mut list = String::from(
        "// @generated by `cargo run --release --bin gen_assets`. Do not edit.\n\n\
         pub const SPRITES: &[(&str, &[u8])] = &[\n",
    );
    for (name, cv) in &sheet {
        cv.save(&format!("assets/sprites/{name}.png"));
        writeln!(list, "    (\"{name}\", include_bytes!(\"../assets/sprites/{name}.png\")),").unwrap();
    }
    list.push_str("];\n\npub const SOUNDS: &[(&str, &[u8])] = &[\n");

    audio::write_wav("assets/audio/music.wav", &audio::music());
    writeln!(list, "    (\"music\", include_bytes!(\"../assets/audio/music.wav\")),").unwrap();
    for name in SFX {
        audio::write_wav(&format!("assets/audio/{name}.wav"), &audio::sfx(name));
        writeln!(list, "    (\"{name}\", include_bytes!(\"../assets/audio/{name}.wav\")),").unwrap();
    }
    list.push_str("];\n");
    fs::write("src/assets_list.rs", list).unwrap();
    println!("Generated {} sprites and {} sounds.", sheet.len(), SFX.len() + 1);
}
